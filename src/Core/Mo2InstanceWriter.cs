using System.Text;

namespace AStoryWealth.Core;

/// <summary>
/// Materializes a ResolvedPlan into a portable MO2 instance folder:
///   instance/
///     ModOrganizer.ini        (game + instance wiring, placeholders for paths)
///     mods/&lt;installAs&gt;/...   (one folder per manifest mod entry)
///     overwrite/
///     profiles/A StoryWealth/ (modlist.txt, plugins.txt, ini tweaks)
///     downloads/              (Nexus archives, verifiable/restartable)
///     install.log             (run log)
/// Order semantics: MO2 modlist.txt lists highest priority FIRST (top = wins
/// overwrites). Addon installPriority ascending = installed earlier = lower
/// priority, so the sorted list is reversed when written.
/// </summary>
public static partial class Mo2InstanceWriter
{
    public static void Scaffold(string instanceDir, string gamePath, string? downloadsDir = null)
    {
        Directory.CreateDirectory(instanceDir);
        Directory.CreateDirectory(Path.Combine(instanceDir, "mods"));
        Directory.CreateDirectory(Path.Combine(instanceDir, "overwrite"));
        Directory.CreateDirectory(downloadsDir ?? Path.Combine(instanceDir, "downloads"));
        var profileDir = Path.Combine(instanceDir, "profiles", "A StoryWealth");
        Directory.CreateDirectory(profileDir);

        // Wabbajack-style fully configured instance: no first-start wizard, game
        // wired, downloads dir set, F4SE launch executable registered.
        var dl = (downloadsDir ?? Path.Combine(instanceDir, "downloads")).Replace('\\', '/');
        var game = gamePath.Replace('\\', '/');
        var ini =
            "[General]\n" +
            "gameName=Fallout 4\n" +
            $"selected_profile=@ByteArray(A StoryWealth)\n" +
            $"gamePath=@ByteArray({game.Replace("/", "\\\\")})\n" +
            "first_start=false\n" +
            "backup_install=false\n" +
            "game_edition=Steam\n" +
            "\n" +
            "[Settings]\n" +
            "check_for_updates=false\n" +
            "profile_local_inis=true\n" +
            "profile_local_saves=true\n" +
            "profile_archive_invalidation=true\n" +
            $"download_directory={dl}\n" +
            "\n" +
            "[Network]\n" +
            "\n" +
            "[customExecutables]\n" +
            "size=2\n" +
            "1\\title=Fallout 4\n" +
            $"1\\binary={game}/Fallout4.exe\n" +
            "1\\hide=true\n" +
            "1\\ownicon=false\n" +
            "1\\toolbar=false\n" +
            "1\\steamAppID=\n" +
            "1\\arguments=\n" +
            "1\\workingDirectory=\n" +
            "2\\title=A StoryWealth (F4SE)\n" +
            $"2\\binary={game}/f4se_loader.exe\n" +
            "2\\hide=false\n" +
            "2\\ownicon=false\n" +
            "2\\toolbar=true\n" +
            "2\\steamAppID=\n" +
            "2\\arguments=\n" +
            $"2\\workingDirectory={game}\n" +
