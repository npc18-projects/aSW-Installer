using System.Text;

namespace AStoryWealth.Core;

/// <summary>
/// Materializes a ResolvedPlan into a portable MO2 instance folder:
///   instance/
///     ModOrganizer.ini        (game + instance wiring, placeholders for paths)
///     mods/&lt;installAs&gt;/...   (one folder per manifest mod entry)
///     overwrite/
///     profiles/A StoryWealth/ (modlist.txt, plugins.txt, ini tweaks)
///     downloads/              (Nexus archives, verifiable/restartable)
///     install.log             (run log)
/// Order semantics: MO2 modlist.txt lists highest priority FIRST (top = wins
/// overwrites). Addon installPriority ascending = installed earlier = lower
/// priority, so the sorted list is reversed when written.
/// </summary>
public static partial class Mo2InstanceWriter
{
    public static void Scaffold(string instanceDir, string gamePath, string? downloadsDir = null)
    {
        Directory.CreateDirectory(instanceDir);
        Directory.CreateDirectory(Path.Combine(instanceDir, "mods"));
        Directory.CreateDirectory(Path.Combine(instanceDir, "overwrite"));
        Directory.CreateDirectory(downloadsDir ?? Path.Combine(instanceDir, "downloads"));
        var profileDir = Path.Combine(instanceDir, "profiles", "A StoryWealth");
        Directory.CreateDirectory(profileDir);

        // Wabbajack-style fully configured instance: no first-start wizard, game
        // wired, downloads dir set, F4SE launch executable registered.
        var dl = (downloadsDir ?? Path.Combine(instanceDir, "downloads")).Replace('\\', '/');
        var game = gamePath.Replace('\\', '/');
        var ini =
            "[General]\n" +
            "gameName=Fallout 4\n" +
            $"selected_profile=@ByteArray(A StoryWealth)\n" +
            $"gamePath=@ByteArray({game.Replace("/", "\\\\")})\n" +
            "first_start=false\n" +
            "backup_install=false\n" +
            "game_edition=Steam\n" +
            "\n" +
            "[Settings]\n" +
            "check_for_updates=false\n" +
            "profile_local_inis=true\n" +
            "profile_local_saves=true\n" +
            "profile_archive_invalidation=true\n" +
            $"download_directory={dl}\n" +
            "\n" +
            "[Network]\n" +
            "\n" +
            "[customExecutables]\n" +
            "size=2\n" +
            "1\\title=Fallout 4\n" +
            $"1\\binary={game}/Fallout4.exe\n" +
            "1\\hide=true\n" +
            "1\\ownicon=false\n" +
            "1\\toolbar=false\n" +
            "1\\steamAppID=\n" +
            "1\\arguments=\n" +
            "1\\workingDirectory=\n" +
            "2\\title=A StoryWealth (F4SE)\n" +
            $"2\\binary={game}/f4se_loader.exe\n" +
            "2\\hide=false\n" +
            "2\\ownicon=false\n" +
            "2\\toolbar=true\n" +
            "2\\steamAppID=\n" +
            "2\\arguments=\n" +
            $"2\\workingDirectory={game}\n" +
            "\n" +
            "[PluginPersistance]\n" +
            "Python%20Proxy\\tryInit=false\n" +
            "\n" +
            "[Profiles]\n" +
            "current_profile=A StoryWealth\n";
        // Audit C3: never overwrite an existing ModOrganizer.ini — an add-on run
        // would otherwise reset the user's configured paths/settings.
        var iniPath = Path.Combine(instanceDir, "ModOrganizer.ini");
        if (!File.Exists(iniPath))
            File.WriteAllText(iniPath, ini, new UTF8Encoding(false));
        InstallLog.Info("mo2", $"scaffolded instance at {instanceDir} (game: {gamePath})");
        SweepStaging(instanceDir);   // unfinished folders from a run that was cancelled or crashed
    }

    private const string ModlistHeader = "# This file was automatically generated by Mod Organizer.";
    private const string SeparatorSuffix = "_separator";

    /// <summary>
    /// Writes the MO2 profile's modlist.txt, plugins.txt and loadorder.txt.
    ///
    /// Orders are computed in ASCENDING priority (last entry wins), matching
    /// Vortex's "later deploys over earlier" model:
    ///   - deploy order: DeployOrder (install phase + before/after modRules);
    ///   - load order:   PluginOrder (collection plugin list + master/ESM rules).
    /// MO2 stores modlist.txt HIGHEST priority first, so the list is reversed on
    /// write and on read. plugins.txt / loadorder.txt are top = loads first.
    /// Add-on runs merge with the existing profile (state and order kept).
    /// </summary>
    /// <param name="skip">installAs values that are not mod folders (game-root mods, optionals).</param>
    /// <param name="gameDir">Game root, used to read vanilla plugin headers.</param>
    public static void WriteLoadFiles(string instanceDir, ManifestResolver.ResolvedPlan plan,
        HashSet<string>? skip = null, string? gameDir = null, bool isAddon = false)
    {
        var profileDir = Path.Combine(instanceDir, "profiles", "A StoryWealth");
        Directory.CreateDirectory(profileDir);
        var addons = plan.InstallOrder.Select(t => t.Addon).Distinct().ToList();

        // ---- deploy order (modlist.txt)
        var mlPath = Path.Combine(profileDir, "modlist.txt");
        var existing = ReadModlist(mlPath)                          // ascending priority; a hand-edited duplicate keeps its last entry
            .GroupBy(e => e.Name, StringComparer.OrdinalIgnoreCase).Select(g => g.Last()).ToList();
        // The structured order (if one ships for this collection) owns its separators: drop stale copies.
        var shipped = addons.Count == 1 && !isAddon ? PriorityOrder.LoadShipped(addons[0].AddonId) : null;
        var ownSeparators = new HashSet<string>(
            (shipped?.Separators ?? []).Select(s => s.Name + SeparatorSuffix), StringComparer.OrdinalIgnoreCase);
        // what earlier add-on runs put in this instance: their separators and mod folders must survive a base re-run
        var registry = AddonRegistry.Load(instanceDir);
        var addonSeparators = new HashSet<string>(
            registry.Addons.Where(a => a.Separator.Length > 0).Select(a => a.Separator + SeparatorSuffix), StringComparer.OrdinalIgnoreCase);
        var addonMods = new HashSet<string>(registry.Addons.SelectMany(a => a.Mods.Select(m => m.Name)), StringComparer.OrdinalIgnoreCase);
        if (shipped is not null)
        {
            // separators an earlier version of the order created that the current one no longer has
            var stale = existing.Where(e => e.Name.EndsWith(SeparatorSuffix, StringComparison.Ordinal)
                && !ownSeparators.Contains(e.Name) && !addonSeparators.Contains(e.Name) && IsInstallerSeparator(instanceDir, e.Name)).Select(e => e.Name).ToList();
            if (stale.Count > 0)
            {
                InstallLog.Info("mo2", $"removing {stale.Count} outdated installer separator(s): {string.Join(", ", stale.Select(s => s[..^SeparatorSuffix.Length]))}");
                RemoveStaleSeparators(instanceDir, stale);
                var gone = new HashSet<string>(stale, StringComparer.OrdinalIgnoreCase);
                existing = existing.Where(e => !gone.Contains(e.Name)).ToList();
            }
        }
        // Mods people put under the "Added mods" separator stay on top (highest priority) across reruns.
        var userTail = new List<string>();
        var addedAt = shipped is null ? -1 : existing.FindIndex(e => e.Name.Equals(PriorityOrder.AddedModsSeparator + SeparatorSuffix, StringComparison.OrdinalIgnoreCase));
        if (addedAt >= 0)
            userTail = existing.Skip(addedAt + 1).Where(e => e.Prefix != '*' && !ownSeparators.Contains(e.Name)).Select(e => e.Name).ToList();
        existing = existing.Where(e => !ownSeparators.Contains(e.Name)).ToList();
        var state =existing.ToDictionary(e => e.Name, e => e.Prefix, StringComparer.OrdinalIgnoreCase);

        List<string> ordered;
        DeployOrder.Report rep;
        string addonSep = "";
        AddonPlacement.Result? placed = null;
        if (isAddon && addons.Count == 1)
        {
            // Add-on run: its own block under its own separator on top of the base list (below "Added mods"),
            // except mods that must deploy before a base mod, which are hoisted in beside it.
            var addon = addons[0];
            var label = AddonPlacement.Label(addon);
            addonSep = label + SeparatorSuffix;
            var planNew = new HashSet<string>(addon.Mods.Where(m => !m.IsAnchor).Select(m => m.InstallAs), StringComparer.OrdinalIgnoreCase);
            var all = existing.Select(e => e.Name).ToList();
            var addedIdx = all.FindIndex(n => n.Equals(PriorityOrder.AddedModsSeparator + SeparatorSuffix, StringComparison.OrdinalIgnoreCase));
            var tail = addedIdx >= 0 ? all.Skip(addedIdx).ToList() : [];
            var head = (addedIdx >= 0 ? all.Take(addedIdx) : all).Where(n => !n.Equals(addonSep, StringComparison.OrdinalIgnoreCase) && !planNew.Contains(n)).ToList();
            placed = AddonPlacement.Place(head, addon, instanceDir, label);
            ordered = [.. placed.Head, .. (placed.Block.Count > 0 ? new[] { addonSep } : []), .. placed.Block, .. tail];
            rep = new DeployOrder.Report(addon.ModRules?.Count ?? 0, 0, 0, 0, [], []);
            InstallLog.Info("mo2", $"add-on \"{label}\": {placed.Block.Count} mod(s) in its own block, {placed.Hoisted.Count} placed inside the base list "
                + $"(must deploy before a base mod), {addon.Mods.Count(m => m.IsAnchor)} already-installed mod(s) used as anchors");
            foreach (var h in placed.Hoisted.Take(10)) InstallLog.Info("mo2", $"  hoisted: {h}");
        }
        else
            (ordered, rep) = DeployOrder.Compute(existing.Select(e => e.Name).ToList(), addons);
        ordered = ordered.Where(n => skip is null || !skip.Contains(n)).ToList();
        // Mods this run installs are (re-)enabled: a stale profile must not leave part of the collection
        // switched off. Mods from other runs (addons, the user's own) keep their enabled state.
        var fromPlan = new HashSet<string>(addons.SelectMany(a => a.Mods).Where(m => !m.IsAnchor).Select(m => m.InstallAs), StringComparer.OrdinalIgnoreCase);
        var merged = ordered.Select(n => (Name: n,
            Prefix: addonSep.Length > 0 && n.Equals(addonSep, StringComparison.OrdinalIgnoreCase) ? '-'
                : fromPlan.Contains(n) ? '+' : state.TryGetValue(n, out var p) ? p : '+')).ToList();
        if (placed is { Block.Count: > 0 }) WriteSeparatorFolders(instanceDir, [addonSep]);
        else if (addonSep.Length > 0) RemoveStaleSeparators(instanceDir, [addonSep]);

        if (shipped is not null)
        {
            // MO2-style structure: separators in the shipped order, the run's mods grouped under them.
            // Every before/after rule and every real file conflict still resolves exactly as in the
            // Vortex-derived order (PriorityOrder.Apply pushes a mod later rather than flip a winner).
            var planMods = addons.SelectMany(a => a.Mods).Where(m => !m.IsOptional || fromPlan.Contains(m.InstallAs))
                .GroupBy(m => m.InstallAs, StringComparer.OrdinalIgnoreCase).Select(g => g.First())
                .Where(m => ordered.Contains(m.InstallAs, StringComparer.OrdinalIgnoreCase)).ToList();
            var planNames = new HashSet<string>(planMods.Select(m => m.InstallAs), StringComparer.OrdinalIgnoreCase);
            var baseline = ordered.Where(planNames.Contains).ToList();
            var ruleEdges = DeployOrder.RuleEdges(addons.SelectMany(a => a.Mods).ToList(), addons.SelectMany(a => a.ModRules ?? []).ToList());
            var preds = PriorityOrder.Constraints(instanceDir, planMods, baseline, ruleEdges);
            var (entries, report) = PriorityOrder.Apply(shipped, planMods, baseline, preds);
            // user-added = under the old "Added mods" separator, still in the list, and not something this run installs or skips
            var present = new HashSet<string>(merged.Select(m => m.Name), StringComparer.OrdinalIgnoreCase);
            var userSet = new HashSet<string>(userTail.Where(n => !planNames.Contains(n) && present.Contains(n)), StringComparer.OrdinalIgnoreCase);
            var others = merged.Where(m => !planNames.Contains(m.Name) && !userSet.Contains(m.Name)).ToList();   // foreign/other-run mods stay at the bottom
            // add-ons installed earlier (their separators and mods) stay above the base list; re-run the add-on to re-place hoisted mods
            var addonOwned = others.Where(m => addonMods.Contains(m.Name) || addonSeparators.Contains(m.Name)).ToList();
            if (addonOwned.Count > 0) others = others.Where(m => !addonOwned.Contains(m)).ToList();
            var mine = userTail.Where(userSet.Contains)
                .Select(n => merged.First(m => m.Name.Equals(n, StringComparison.OrdinalIgnoreCase))).ToList();
            WriteSeparatorFolders(instanceDir, entries.Where(e => e.IsSeparator).Select(e => e.Name + SeparatorSuffix));
            // separators of this order that ended up with no mods (e.g. "Sim Settlements 2" when that group is left out)
            // must not linger as folders, or MO2 would add them back to the list
            var emitted = new HashSet<string>(entries.Where(e => e.IsSeparator).Select(e => e.Name + SeparatorSuffix), StringComparer.OrdinalIgnoreCase);
            RemoveStaleSeparators(instanceDir, ownSeparators.Where(n => !emitted.Contains(n)));
            var entryList = entries.Select(e => e.IsSeparator
                ? (Name: e.Name + SeparatorSuffix, Prefix: '-')
                : (Name: e.Name, Prefix: '+')).ToList();
            // add-ons sit on top of the base list but still under "Added mods"
            var addedAt2 = entryList.FindIndex(e => e.Name.Equals(PriorityOrder.AddedModsSeparator + SeparatorSuffix, StringComparison.OrdinalIgnoreCase));
            if (addedAt2 >= 0) entryList.InsertRange(addedAt2, addonOwned); else entryList.AddRange(addonOwned);
            merged = [.. others, .. entryList, .. mine];
            if (mine.Count > 0) InstallLog.Info("mo2", $"kept {mine.Count} user-added mod(s) under \"{PriorityOrder.AddedModsSeparator}\"");
            InstallLog.Info("mo2",
                $"structured priority order: {entries.Count(e => e.IsSeparator)} separators, {report.Mods} mods "
                + $"({report.Unplaced} placed by category, {report.PushedLater} moved to a later separator by rules/file conflicts, {report.OrderFixes} reordered)");
        }

        // Mods this run leaves out (an unticked group, optional mods) that are already extracted on disk: list them
        // disabled at the bottom, so MO2 does not re-discover the folders and drop them at the top of the list.
        if (skip is not null)
            foreach (var n in skip.OrderByDescending(x => x, StringComparer.OrdinalIgnoreCase))
                if (!merged.Any(m => m.Name.Equals(n, StringComparison.OrdinalIgnoreCase))
                    && Directory.Exists(Path.Combine(instanceDir, "mods", SafeName(n, "installAs"))))
                    merged.Insert(0, (Name: n, Prefix: (char)45));

        InstallLog.Info("mo2",
            $"deploy order: {merged.Count} mods; {rep.Rules} before/after rules → {rep.EdgesApplied} edges applied, "
            + $"{rep.Unresolved} unresolved, {rep.CyclesBroken} cycle(s) broken");
        foreach (var u in rep.UnresolvedDetails.Take(15)) InstallLog.Info("mo2", $"modRule inert (endpoint mod not in this collection): {u}");
        if (rep.UnresolvedDetails.Count > 15)
            InstallLog.Info("mo2", $"… and {rep.UnresolvedDetails.Count - 15} more inert modRules");
        foreach (var c in rep.CycleDetails) InstallLog.Warn("mo2", $"modRule cycle: {c}");

        var modlist = new StringBuilder();
        modlist.AppendLine(ModlistHeader);
        foreach (var (name, prefix) in Enumerable.Reverse(merged)) modlist.Append(prefix).AppendLine(name);
        File.WriteAllText(mlPath, modlist.ToString(), new UTF8Encoding(false));

        // ---- load order (plugins.txt + loadorder.txt)
        var plPath = Path.Combine(profileDir, "plugins.txt");
        var loPath = Path.Combine(profileDir, "loadorder.txt");
        var current = new List<(string Name, bool Enabled)>();
        if (File.Exists(plPath))
            foreach (var l in File.ReadAllLines(plPath))
            {
                var t = l.Trim();
                if (t.Length == 0 || t[0] == '#') continue;
                if (t[0] is '*' or '+') current.Add((t[1..].Trim(), true));
                else current.Add((t, false));
            }
        var enabled = new Dictionary<string, bool>(StringComparer.OrdinalIgnoreCase);
        var desired = new List<string>();
        foreach (var (n, en) in current)
            if (enabled.TryAdd(n, en)) desired.Add(n);
        foreach (var p in plan.PluginState)          // collection order; disabled ones keep their slot
            if (enabled.TryAdd(p.Plugin, p.Enabled)) desired.Add(p.Plugin);

        var paths = LocatePlugins(instanceDir, merged, gameDir);

        // A plugin whose file is nowhere (its mod is optional and not installed, or disabled) stays out of
        // both lists — MO2 would only log "Plugin not found" for it.
        var absent = desired.Where(n => !paths.ContainsKey(n)).ToList();
        if (absent.Count > 0)
        {
            desired = desired.Where(paths.ContainsKey).ToList();
            InstallLog.Info("mo2", $"left {absent.Count} plugin(s) out of the load order (no file on disk — optional/uninstalled mods): {string.Join(", ", absent.Take(8))}{(absent.Count > 8 ? ", …" : "")}");
        }
        // A plugin that sits in an installed mod but that no list mentions (the collection's plugin list leaves some out) is
        // switched on. Left out, MO2 adds it itself the first time it starts, and adds it switched off.
        var dataDir = gameDir is null ? null : Path.GetFullPath(Path.Combine(gameDir, "Data")) + Path.DirectorySeparatorChar;
        var unlisted = paths.Where(kv => !enabled.ContainsKey(kv.Key)
                && (dataDir is null || !Path.GetFullPath(kv.Value).StartsWith(dataDir, StringComparison.OrdinalIgnoreCase)))
            .Select(kv => kv.Key).OrderBy(n => n, StringComparer.OrdinalIgnoreCase).ToList();
        foreach (var n in unlisted) { enabled[n] = true; desired.Add(n); }
        if (unlisted.Count > 0)
            InstallLog.Info("mo2", $"{unlisted.Count} plugin(s) in installed mods weren't in any list; switched on: {string.Join(", ", unlisted.Take(8))}{(unlisted.Count > 8 ? ", …" : "")}");
        var headers =new Dictionary<string, PluginOrder.Info?>(StringComparer.OrdinalIgnoreCase);
        PluginOrder.Info? Header(string name)
        {
            if (headers.TryGetValue(name, out var h)) return h;
            return headers[name] = paths.TryGetValue(name, out var path) ? PluginOrder.ReadHeader(path) : null;
        }
        var rules = addons.SelectMany(a => PluginOrder.ParseRules(a.PluginRulesJson)).ToList();
        var (loadOrder, notes) = PluginOrder.Arrange(desired, Header, rules);
        foreach (var n in notes.Where(n => !n.Contains("needs master")).Take(25)) InstallLog.Warn("mo2", $"load order: {n}");
        // A plugin whose master isn't installed (an optional mod, or the SS2 group left out) would stop the game loading.
        var reg = AddonRegistry.LoadStrict(instanceDir);
        foreach (var n in loadOrder.Where(n => reg.AutoDisabled.Contains(n, StringComparer.OrdinalIgnoreCase)))
            enabled[n] = true;   // turned off by an earlier run; stays on if its master has turned up since
        var noMaster = PluginOrder.MissingMasters(loadOrder, enabled, Header);
        foreach (var (plugin, master) in noMaster)
            enabled[plugin] = false;
        var autoNow = reg.AutoDisabled.Where(n => !loadOrder.Contains(n, StringComparer.OrdinalIgnoreCase))
            .Concat(noMaster.Select(x => x.Plugin)).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        if (!autoNow.SequenceEqual(reg.AutoDisabled, StringComparer.OrdinalIgnoreCase))
        { reg.AutoDisabled = autoNow; AddonRegistry.Save(instanceDir, reg); }
        if (noMaster.Count > 0)
            InstallLog.Warn("mo2", $"turned off {noMaster.Count} plugin(s) whose master isn't installed: " +
                string.Join("; ", noMaster.Take(12).Select(x => $"{x.Plugin} (needs {x.Master})")) + (noMaster.Count > 12 ? "; …" : ""));

        var pl = new StringBuilder();
        var lo = new StringBuilder();
        pl.AppendLine("# This file was automatically generated by Mod Organizer.");
        lo.AppendLine("# This file was automatically generated by Mod Organizer.");
        // MO2 lists the game's own masters first in loadorder.txt (plugins.txt omits them).
        if (gameDir is not null)
            foreach (var v in PluginOrder.VanillaMasters)
                if (File.Exists(Path.Combine(gameDir, "Data", v)) && !loadOrder.Contains(v, StringComparer.OrdinalIgnoreCase))
                    lo.AppendLine(v);
        foreach (var n in loadOrder)
        {
            pl.Append(enabled[n] ? "*" : "").AppendLine(n);
            lo.AppendLine(n);
        }
        File.WriteAllText(plPath, pl.ToString(), new UTF8Encoding(false));
        File.WriteAllText(loPath, lo.ToString(), new UTF8Encoding(false));
        InstallLog.Info("mo2",
            $"wrote modlist.txt ({merged.Count} mods), plugins.txt/loadorder.txt ({loadOrder.Count} plugins, {loadOrder.Count(n => enabled[n])} enabled)");

        if (isAddon && addons.Count == 1 && placed is not null)
        {
            var addon = addons[0];
            var sharedMd5 = registry.Addons.Where(a => !a.Id.Equals(addon.AddonId, StringComparison.OrdinalIgnoreCase))
                .SelectMany(a => a.Mods.Select(m => m.Md5)).Where(h => h.Length > 0).ToHashSet(StringComparer.OrdinalIgnoreCase);
            AddonRegistry.Upsert(instanceDir, new InstalledAddon
            {
                Id = addon.AddonId,
                Name = addon.Name,
                Revision = addon.Version,
                Separator = placed.Block.Count > 0 ? AddonPlacement.Label(addon) : "",
                Mods = addon.Mods.Where(m => (skip is null || !skip.Contains(m.InstallAs)) && (!m.IsAnchor || sharedMd5.Contains(m.Nexus?.Md5 ?? "")))
                    .GroupBy(m => m.InstallAs, StringComparer.OrdinalIgnoreCase)
                    .Select(g => new InstalledAddonMod { Name = g.Key, Md5 = g.First().Nexus?.Md5 ?? "" }).ToList(),
                Hoisted = placed.Hoisted.ToList(),
                InstalledUtc = DateTime.UtcNow,
            });
        }

        // Read-back guard: MO2 saving stale state over these files is the #1
        // profile-clobber cause — verify the write landed, including order.
        if (File.ReadAllText(mlPath) != modlist.ToString())
            InstallLog.Error("mo2", "modlist.txt verify failed — content differs (MO2 likely rewrote it; close MO2 and re-run finalize)");
    }

    /// <summary>modlist.txt entries in ASCENDING priority. A file starting with
    /// MO2's "#" header is MO2 format (highest first, reversed here); a headerless
    /// file comes from an older build that wrote ascending order directly.</summary>
    private static List<(string Name, char Prefix)> ReadModlist(string path)
    {
        var list = new List<(string, char)>();
        if (!File.Exists(path)) return list;
        var lines = File.ReadAllLines(path);
        var mo2Format = lines.Length > 0 && lines[0].TrimStart().StartsWith('#');
        foreach (var l in lines)
            if (l.Trim() is { Length: > 1 } line && line[0] is '+' or '-' or '*')
                list.Add((line[1..].Trim(), line[0]));
        if (mo2Format) list.Reverse();
        return list;
    }

    /// <summary>plugin file name → winning path: later (higher priority) enabled mods override
    /// earlier ones; the game's own Data folder is the fallback for vanilla/CC plugins.</summary>
    public static Dictionary<string, string> LocatePlugins(
        string instanceDir, IReadOnlyList<(string Name, char Prefix)> ascending, string? gameDir)
    {
        var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        if (gameDir is not null)
        {
            var data = Path.Combine(gameDir, "Data");
            if (Directory.Exists(data))
                foreach (var f in Directory.EnumerateFiles(data))
                    if (IsPlugin(f)) map[Path.GetFileName(f)] = f;
        }
        foreach (var (name, prefix) in ascending)
        {
            if (prefix != '+') continue;
            string dir;
            try { dir = Path.Combine(instanceDir, "mods", SafeName(name, "installAs")); }
            catch (InvalidOperationException) { continue; }
            if (!Directory.Exists(dir)) continue;
            foreach (var f in Directory.EnumerateFiles(dir))
                if (IsPlugin(f)) map[Path.GetFileName(f)] = f;
        }
        return map;
    }

    private static bool IsPlugin(string path)
    {
        var ext = Path.GetExtension(path);
        return ext.Equals(".esp", StringComparison.OrdinalIgnoreCase)
            || ext.Equals(".esm", StringComparison.OrdinalIgnoreCase)
            || ext.Equals(".esl", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>Extract a downloaded archive into mods/&lt;installAs&gt; via 7z. Hidden window. Returns (elapsedSec, bytesWritten).
    /// rootLayout: destination is mods/&lt;installAs&gt;/Root/ (Root Builder convention for Vortex "dinput" mods).</summary>
    public static (double sec, long bytes) Materialize(string instanceDir, string installAs, string archivePath, bool rootLayout = false)
    {
        installAs = SafeName(installAs, "installAs");
        var dest = Path.Combine(instanceDir, "mods", installAs);
        if (rootLayout) dest = Path.Combine(dest, "Root");
        // Extract to a staging sibling and rename only on success: a crash or
        // failed extraction must never leave a half-filled folder that a later
        // run mistakes for "already installed" (audit C2).
        var staging = dest + ".part";
        try { if (Directory.Exists(staging)) InstallRunner.DeleteTree(staging); } catch { }
        Directory.CreateDirectory(staging);
        var sw = System.Diagnostics.Stopwatch.StartNew();
        var (exitCode, se, so) = SevenZip.Extract(archivePath, staging);
        sw.Stop();
        if (exitCode != 0)
        {
            InstallLog.Error("mo2", $"7z exit {exitCode} extracting {Path.GetFileName(archivePath)}: {se} {so}");
            try { InstallRunner.DeleteTree(staging); } catch { }
            throw new InvalidOperationException($"archive extraction failed: {archivePath}");
        }
        StripWrapper(staging, installAs);
        // Commit: staging → dest (dest must not exist at this point; the caller
        // only gets here for uninstalled mods).
        try { if (Directory.Exists(dest)) InstallRunner.DeleteTree(dest); } catch { }
        try
        {
            Directory.Move(staging, dest);
        }
        catch (IOException)
        {
            // Cross-device or transient lock — fall back to a copy-based move.
            CopyDirectory(staging, dest);
            InstallRunner.DeleteTree(staging);
        }
        var count = Directory.EnumerateFileSystemEntries(dest).Count();
        var bytes = CountBytes(dest);
        var sec = Math.Max(sw.Elapsed.TotalSeconds, 0.001);
        InstallLog.Info("mo2", $"materialized '{installAs}' ({count} entries, {bytes / 1_000_000.0:F1} MB in {sec:F1}s — {bytes / 1_000_000.0 / sec:F1} MB/s)");
        return (sw.Elapsed.TotalSeconds, bytes);
    }

    /// <summary>Recursive copy used as a fallback when a rename isn't possible.</summary>
    private static void CopyDirectory(string src, string dst)
    {
        Directory.CreateDirectory(dst);
        foreach (var f in Directory.GetFileSystemEntries(src, "*", SearchOption.AllDirectories))
        {
            var t = Path.Combine(dst, Path.GetRelativePath(src, f));
            Directory.CreateDirectory(Path.GetDirectoryName(t)!);
            if (Directory.Exists(f)) Directory.CreateDirectory(t);
            else File.Copy(f, t, true);
        }
    }

    /// <summary>Vortex convention: if an archive's root is a single directory
    /// with nothing beside it, that wrapper is stripped ("Main"-folder mods).
    /// Applies to whole-archive dumps.</summary>
    public static void StripWrapper(string dir, string label)
    {
        if (!Directory.Exists(dir)) return;
        var entries = Directory.GetFileSystemEntries(dir);
        var rootEntries = entries.Where(e => Path.GetFileName(e) != ".asw-stripped").ToList();
        // Legacy marker files from older builds: MO2 flags them as conflicts - remove.
        foreach (var m in rootEntries.Where(e => Path.GetFileName(e) == ".asw-stripped").ToList())
            try { File.Delete(m); } catch { }
        rootEntries.RemoveAll(e => Path.GetFileName(e) == ".asw-stripped");

        // Vortex convention (verified against collection hashes[] ground truth):
        // 1) a top-level "Data" folder is ALWAYS a wrapper — its children go to
        //    the mod root, siblings (readmes etc.) stay where they are;
        // 2) a single folder child named like the mod (the install name minus
        //    the "A Storywealth - " prefix, optional " (...)" variant suffixes
        //    ignored) is a mod-name wrapper — its contents replace the folder.
        // Root Builder mods live at mods/<n>/Root/ — Root IS the layout, never
        // a wrapper. A lone Meshes/Textures/etc. folder is likewise real structure.
        var dataDir = rootEntries.FirstOrDefault(e =>
            Path.GetFileName(e).Equals("Data", StringComparison.OrdinalIgnoreCase) && Directory.Exists(e));
        if (dataDir != null)
        {
            foreach (var e in Directory.GetFileSystemEntries(dataDir, "*", SearchOption.TopDirectoryOnly))
            {
                var target = Path.Combine(dir, Path.GetFileName(e));
                if (Directory.Exists(e))
                {
                    foreach (var f in Directory.GetFileSystemEntries(e, "*", SearchOption.AllDirectories))
                    {
                        var t = Path.Combine(target, Path.GetRelativePath(e, f));
                        Directory.CreateDirectory(Path.GetDirectoryName(t)!);
                        if (Directory.Exists(f)) Directory.CreateDirectory(t);
                        else File.Copy(f, t, true);
                    }
                }
                else if (!File.Exists(target)) Directory.Move(e, target);
                else File.Copy(e, target, true);
            }
            Directory.Delete(dataDir, true);
            InstallLog.Info("mo2", $"{label}: unwrapped 'Data' folder to mod root (Vortex convention)");
            StripWrapper(dir, label); // re-evaluate: another wrapper may now be exposed
            return;
        }

        // 3) nested wrappers: Archive > "Mod Name (version)" > Data, where the
        //    intermediate name is unpredictable (version/build suffix), so the
        //    name rule below cannot match. Walk the chain of single-directory
        //    children (Root/ and fomod/ stop the walk — they are real layout);
        //    if the chain end contains a Data folder, strip the intermediates
        //    and let the Data-unwrap above run on the next call.
        var chainEnd = dir;
        var chain = new List<string>();
        while (true)
        {
            var kids = Directory.GetFileSystemEntries(chainEnd);
            if (kids.Length != 1 || !Directory.Exists(kids[0])) break;
            var kid = Path.GetFileName(kids[0]);
            if (kid is "Root" or "fomod" or "Data" or "data") break;
            chain.Add(kids[0]);
            chainEnd = kids[0];
        }
        if (chain.Count > 0 && Directory.Exists(Path.Combine(chainEnd, "Data")))
        {
            foreach (var e in Directory.GetFileSystemEntries(chainEnd))
            {
                var target = Path.Combine(dir, Path.GetFileName(e));
                if (Directory.Exists(e))
                {
                    foreach (var f in Directory.GetFileSystemEntries(e, "*", SearchOption.AllDirectories))
                    {
                        var t = Path.Combine(target, Path.GetRelativePath(e, f));
                        Directory.CreateDirectory(Path.GetDirectoryName(t)!);
                        if (Directory.Exists(f)) Directory.CreateDirectory(t);
                        else File.Copy(f, t, true);
                    }
                }
                else if (!File.Exists(target)) Directory.Move(e, target);
                else File.Copy(e, target, true);
            }
            for (var i = chain.Count - 1; i >= 0; i--) // deepest first — copies leave the tree in place
                Directory.Delete(chain[i], true);
            InstallLog.Info("mo2",
                $"{label}: stripped {chain.Count} nested wrapper folder(s) above 'Data' ({string.Join(" > ", chain.Select(Path.GetFileName))})");
            StripWrapper(dir, label); // 'Data' now sits at the mod root — unwrap it too
            return;
        }

        var expectName = Path.GetFileName(dir);
        if (expectName.EndsWith(".part", StringComparison.OrdinalIgnoreCase))
            expectName = expectName[..^".part".Length];   // FOMOD staging dirs are dest + ".part"
        if (expectName.StartsWith("A Storywealth - ", StringComparison.OrdinalIgnoreCase))
            expectName = expectName["A Storywealth - ".Length..];
        var paren = expectName.IndexOf(" (", StringComparison.Ordinal);
        if (paren > 0) expectName = expectName[..paren];

        if (rootEntries.Count == 1 && Directory.Exists(rootEntries[0]))
        {
            var inner = rootEntries[0];
            var innerName = Path.GetFileName(inner);
            // General rule (2026-10-17 sweep): the only top-level child is a
            // directory that is NOT a Data-structure name (BodySlide/Textures/
            // Scopes/... are real Data content and must stay) — treat it as a
            // wrapper even when its name does not resemble the mod name.
            // Covers archives nesting content in 'Mod Name 1.15', 'Mod_Name_v1.2.0',
            // 'aSWFaceGen-Main', "Curie's (Robot) Facelift", etc.
            if (innerName != "Root" && (innerName == "Data" ||
                !IsDataLayoutName(innerName) ||
                innerName.Equals(expectName, StringComparison.OrdinalIgnoreCase) ||
                innerName.Equals(Path.GetFileName(dir), StringComparison.OrdinalIgnoreCase)))
            {
                foreach (var e in Directory.GetFileSystemEntries(inner))
                {
                    var target = Path.Combine(dir, Path.GetFileName(e));
                    if (Directory.Exists(target))
                    {
                        foreach (var f in Directory.GetFileSystemEntries(e, "*", SearchOption.AllDirectories))
                        {
                            var t = Path.Combine(target, Path.GetRelativePath(e, f));
                            Directory.CreateDirectory(Path.GetDirectoryName(t)!);
                            if (Directory.Exists(f)) Directory.CreateDirectory(t);
                            else File.Copy(f, t, true);
                        }
                    }
                    else if (!File.Exists(target)) Directory.Move(e, target);
                    else File.Copy(e, target, true);
                }
                Directory.Delete(inner, true);
                InstallLog.Info("mo2", $"{label}: stripped wrapper folder '{innerName}' (Vortex convention)");
                StripWrapper(dir, label);   // "Mod-123-1/Replacer/plugin.esp": the next folder down can be a wrapper too
                return;
            }
        }
    }

