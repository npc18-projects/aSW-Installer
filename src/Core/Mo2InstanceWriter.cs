    private static bool IsDataLayoutName(string name) => DataLayoutNames.Contains(name.Trim());

    /// <summary>
    /// FOMOD mods: extract to staging, apply the collection's option selections
    /// via FomodResolver, and move only the selected files into mods/&lt;installAs&gt;.
    /// Falls back to a whole-archive dump (with a loud log line) if the FOMOD
    /// cannot be resolved, so a run never fails over an odd installer.
    /// </summary>
    public static (double sec, long bytes) MaterializeFomod(string instanceDir, string installAs,
        string archivePath, string choicesJson)
    {
        var sw = System.Diagnostics.Stopwatch.StartNew();
        installAs = SafeName(installAs, "installAs");
        var dest = Path.Combine(instanceDir, "mods", installAs);
        FomodResolver.InstallPlan plan;
        try
        {
            // Resolve INSIDE the try: a malformed ModuleConfig or a missing 7z
            // must fall back to a whole-archive dump, never abort the run.
            plan = FomodResolver.Resolve(archivePath, choicesJson);
        }
        catch (Exception rex)
        {
            InstallLog.Warn("fomod", $"{installAs}: FOMOD resolution failed ({rex.Message}) — falling back to whole-archive dump");
            return Materialize(instanceDir, installAs, archivePath);
        }
        foreach (var issue in plan.Issues)
            InstallLog.Warn("fomod", $"{installAs}: {issue}");
        if (plan.Files.Count == 0)
        {
            InstallLog.Warn("fomod",
                $"{installAs}: FOMOD resolution produced no files — falling back to whole-archive dump (this mod's folder will contain unselected options)");
            return Materialize(instanceDir, installAs, archivePath);
        }

        var staging = Path.Combine(instanceDir, "tmp-fomod", SafeName(installAs, "staging"));
        try
        {
            // Read-only files from a previous failed extraction make plain
            // Directory.Delete throw UnauthorizedAccess (the CustomControlMap
            // bug class) — DeleteTree clears attributes first.
            try { if (Directory.Exists(staging)) InstallRunner.DeleteTree(staging); } catch { }
            Directory.CreateDirectory(staging);
            var sevenZip = SevenZip.ExePath;
            var psi = new System.Diagnostics.ProcessStartInfo
            {
                FileName = sevenZip,
                Arguments = $"x \"{archivePath}\" -o\"{staging}\" -y -bso0 -bsp0",
                UseShellExecute = false,
                CreateNoWindow = true,
                WindowStyle = System.Diagnostics.ProcessWindowStyle.Hidden,
                RedirectStandardError = true,
                RedirectStandardOutput = true,
            };
            using (var proc = System.Diagnostics.Process.Start(psi)!)
            {
                var se = proc.StandardError.ReadToEnd();
                proc.WaitForExit();
                if (proc.ExitCode != 0)
                    throw new InvalidOperationException($"staging extraction failed: {se.Trim()}");
            }
            // FOMOD sources are relative to the mod's data root; a single
            // top-level wrapper folder must be stripped before mapping.
            if (FirstSourceMissing()) StripWrapper(staging, installAs);   // sources like "data\X" are relative to the archive root: only unwrap when they do not resolve as-is

            // Archive-root tolerance: some archives nest everything inside one
            // top-level folder named after the uploader's variant ("... - 1.0"),
            // which StripWrapper's name rules don't catch. If the plan's first
            // source is missing at the staging root but exists under a single
            // top-level directory, merge that directory's contents up.
            bool FirstSourceMissing()
            {
                var f0 = plan.Files.FirstOrDefault();
                if (f0 == null) return false;
                var rel = f0.Source.Trim().TrimStart('.', '/', '\\').Replace('/', Path.DirectorySeparatorChar);
                return !Directory.Exists(Path.Combine(staging, rel)) && !File.Exists(Path.Combine(staging, rel));
            }
            if (FirstSourceMissing())
            {
                var tops = Directory.GetDirectories(staging);
                if (tops.Length == 1 && Path.GetFileName(tops[0]) != "Root")
                {
                    foreach (var e in Directory.GetFileSystemEntries(tops[0], "*", SearchOption.TopDirectoryOnly))
                    {
                        var target = Path.Combine(staging, Path.GetFileName(e));
                        if (Directory.Exists(e))
                        {
                            foreach (var f in Directory.GetFileSystemEntries(e, "*", SearchOption.AllDirectories))
                            {
                                var t = Path.Combine(target, Path.GetRelativePath(e, f));
                                Directory.CreateDirectory(Path.GetDirectoryName(t)!);
                                if (Directory.Exists(f)) Directory.CreateDirectory(t);
                                else File.Copy(f, t, true);
                            }
                        }
                        else if (!File.Exists(target)) Directory.Move(e, target);
                        else File.Copy(e, target, true);
                    }
                    Directory.Delete(tops[0], true);
                    InstallLog.Info("fomod", $"{installAs}: merged archive-root folder '{Path.GetFileName(tops[0])}' up one level (variant wrapper)");
                }
            }

            // Fresh destination: a prior run's whole-archive dump (or stale
            // option folders) must never survive a successful FOMOD install.
            try { if (Directory.Exists(dest)) InstallRunner.DeleteTree(dest); } catch { }
            Directory.CreateDirectory(dest);
            long bytes = 0; var copied = 0; var missing = 0;
            foreach (var (src, dst) in plan.Files)
            {
                var source = src.Trim().TrimStart('.', '/', '\\');
                var sourcePath = Path.GetFullPath(Path.Combine(staging, source.Replace('/', Path.DirectorySeparatorChar)));
                // Empty/"." destination = archive root: FOMOD default is the file's
                // own name inside the destination (not a rename to the folder).
                var d = dst.Trim().TrimStart('.', '/', '\\');
                var dstFull = Path.GetFullPath(Path.Combine(dest, d.Replace('/', Path.DirectorySeparatorChar)));
                bool dstIsDir = d.Length == 0 || d.EndsWith("/") || d.EndsWith("\\") || Directory.Exists(dstFull);
                var stagingFull = Path.GetFullPath(staging);
                if (!stagingFull.EndsWith(Path.DirectorySeparatorChar)) stagingFull += Path.DirectorySeparatorChar;
                var destFull = Path.GetFullPath(dest);
                if (!destFull.EndsWith(Path.DirectorySeparatorChar)) destFull += Path.DirectorySeparatorChar;
                if (!sourcePath.StartsWith(stagingFull, StringComparison.OrdinalIgnoreCase) ||
                    (!dstIsDir && !dstFull.StartsWith(destFull, StringComparison.OrdinalIgnoreCase)))
                { missing++; continue; }
                bool isDir = Directory.Exists(sourcePath) || source.EndsWith("/");
                string[] sources;
                if (isDir && Directory.Exists(sourcePath))
                    sources = Directory.EnumerateFiles(sourcePath, "*",
                        new EnumerationOptions { RecurseSubdirectories = true, IgnoreInaccessible = true }).ToArray();
                else if (File.Exists(sourcePath))
                    sources = [sourcePath];
                else { missing++; continue; }
                foreach (var f in sources)
                {
                    var rel = isDir ? f.Substring(sourcePath.Length).TrimStart('\\', '/') : "";
                    string target;
                    if (isDir)
                        target = Path.Combine(dstIsDir ? Path.Combine(dest, d.Replace('/', Path.DirectorySeparatorChar)) : dstFull,
                            rel.Replace('/', Path.DirectorySeparatorChar));
                    else
                        target = dstIsDir && d.Length > 0
                            ? Path.Combine(dest, d.Replace('/', Path.DirectorySeparatorChar), Path.GetFileName(f))
                            : d.Length == 0 ? Path.Combine(dest, Path.GetFileName(f)) : dstFull;
                    Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                    // Copy, never Move: the same source is often mapped twice
                    // (base plugin + conditional pattern) — a move would drop it.
                    try { File.Copy(f, target, overwrite: true); }
                    catch (UnauthorizedAccessException)
                    { // archive may carry read-only attributes
                        if (File.Exists(target)) { try { File.SetAttributes(target, FileAttributes.Normal); } catch { } }
                        File.Copy(f, target, overwrite: true);
                    }
                    var attr = File.GetAttributes(target);
                    if ((attr & FileAttributes.ReadOnly) != 0)
                        File.SetAttributes(target, attr & ~FileAttributes.ReadOnly);
                    bytes += new FileInfo(target).Length;
                    copied++;
                }
            }
            var sec = Math.Max(sw.Elapsed.TotalSeconds, 0.001);
            InstallLog.Info("mo2", $"materialized '{installAs}' (fomod: {copied} files, {bytes / 1_000_000.0:F1} MB in {sec:F1}s — {bytes / 1_000_000.0 / sec:F1} MB/s{(missing > 0 ? $", {missing} unmapped sources skipped" : "")})");
            return (sec, bytes);
        }
        catch (Exception ex)
        {
            InstallLog.Warn("fomod", $"{installAs}: FOMOD materialization failed ({ex.Message}) — falling back to whole-archive dump");
            try { if (Directory.Exists(dest)) InstallRunner.DeleteTree(dest); } catch { }
            return Materialize(instanceDir, installAs, archivePath);
        }
        finally
        {
            try { if (Directory.Exists(staging)) InstallRunner.DeleteTree(staging); } catch { }
        }
    }

    private static long CountBytes(string dir)
    {
        long total = 0;
        foreach (var f in Directory.EnumerateFiles(dir, "*", System.IO.SearchOption.AllDirectories))
        { try { total += new FileInfo(f).Length; } catch { } }
        return total;
    }

    /// <summary>Archive cache path for a mod — downloads/&lt;modId&gt;-&lt;fileId&gt;-&lt;filename&gt;.</summary>
    public static string ArchivePath(string instanceDir, ModEntry mod, string fileName, string? downloadsDir = null)
    {
        var safe = string.Join("_", fileName.Split(Path.GetInvalidFileNameChars()));
        return Path.Combine(downloadsDir ?? Path.Combine(instanceDir, "downloads"),
            $"{mod.Nexus!.ModId}-{mod.Nexus.FileId}-{SafeName(safe, "fileName")}");
    }

    /// <summary>
    /// Sanitizes a name that came from the network so it cannot break out of a
    /// quoted 7z command line or escape the downloads folder: control chars,
    /// quotes and ".." sequences become underscores, leading dashes/dots get a
    /// prefix. Throws only on an empty name.
    /// </summary>
    public static string SafeName(string name, string what)
    {
        if (string.IsNullOrWhiteSpace(name))
            throw new InvalidOperationException($"{what}: empty name");
        name = name.Trim();
        var chars = name.Select(c => c == '"' || char.IsControl(c) ? '_' : c);
        name = new string(chars.ToArray());
        while (name.Contains("..")) name = name.Replace("..", "_");
        if (name.StartsWith('-') || name.StartsWith('.')) name = "_" + name;
        return name;
    }

    /// <summary>Registers collection tools[] as MO2 custom executables by
    /// merging the [customExecutables] section of ModOrganizer.ini. Idempotent:
    /// existing titles are kept untouched, only missing tools are appended.
    /// Exe paths are resolved against the game root (collection uses
    /// game-root-relative paths like "Data\Tools\...").</summary>
    /// <summary>True when a game-relative path (e.g. Data/Tools/X.exe) exists inside a mod folder,
    /// i.e. MO2 will serve it through the virtual file system.</summary>
    private static bool ExistsInMods(string instanceDir, string gameRoot, string exe)
    {
        var rel = Path.GetRelativePath(gameRoot, exe);
        if (rel.StartsWith("..", StringComparison.Ordinal)) return false;
        var mods = Path.Combine(instanceDir, "mods");
        if (!Directory.Exists(mods)) return false;
        if (rel.StartsWith("Data" + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
        {
            rel = rel["Data".Length..].TrimStart(Path.DirectorySeparatorChar);
            return Directory.EnumerateDirectories(mods).Any(d => File.Exists(Path.Combine(d, rel)));
        }
        // game-folder file shipped by a Root Builder mod (e.g. f4se_loader.exe)
        return Directory.EnumerateDirectories(mods).Any(d => File.Exists(Path.Combine(d, "Root", rel)));
    }

    /// <summary>Where MO2 should launch a collection tool from: the instance Tools folder when
    /// the tool lives there (Data\Tools\X → Tools\X), else the game-root path.</summary>
    private static (string Exe, string Cwd)? ResolveTool(string instanceDir, string gameRoot, ToolEntry t)
    {
        // ModOrganizer.ini is a Qt INI: backslashes are escape characters ("D:\Games" reads back as
        // "D:ames"), so every path MO2 should read must use forward slashes.
        if (ResolveToolRaw(instanceDir, gameRoot, t) is not var (exe, cwd)) return null;
        return (exe.Replace(Path.DirectorySeparatorChar, '/'), cwd.Replace(Path.DirectorySeparatorChar, '/'));
    }

    private static (string Exe, string Cwd)? ResolveToolRaw(string instanceDir, string gameRoot, ToolEntry t)
    {
        var exe = Path.IsPathRooted(t.Exe!) ? t.Exe! : Path.Combine(gameRoot, t.Exe!.Replace('/', Path.DirectorySeparatorChar));
        var dataTools = Path.Combine(gameRoot, "Data", ToolsDirName) + Path.DirectorySeparatorChar;
        if (exe.StartsWith(dataTools, StringComparison.OrdinalIgnoreCase))
        {
            var local = Path.Combine(ToolsDir(instanceDir), exe[dataTools.Length..]);
            if (File.Exists(local))
                return (local, Path.GetDirectoryName(local)!);
        }
        var relGame = Path.GetRelativePath(gameRoot, exe);
        if (!File.Exists(exe) && !relGame.StartsWith("..", StringComparison.Ordinal)
            && !relGame.StartsWith("Data" + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)
            && FindRootFile(instanceDir, relGame) is { } rootExe)
            return (rootExe, gameRoot);
        if (!File.Exists(exe) && !ExistsInMods(instanceDir, gameRoot, exe)) return null;
        var cwd = string.IsNullOrWhiteSpace(t.Cwd) ? gameRoot : Path.Combine(gameRoot, t.Cwd.Replace('/', Path.DirectorySeparatorChar));
        return (exe, cwd);
    }

    public static void WriteCustomExecutables(string instanceDir, string gameRoot, List<ToolEntry> tools)
    {
        var usable = tools.Where(t => !string.IsNullOrWhiteSpace(t.Name) && !string.IsNullOrWhiteSpace(t.Exe)).ToList();
        if (usable.Count == 0) return;
        var iniPath = Path.Combine(instanceDir, "ModOrganizer.ini");
        if (!File.Exists(iniPath)) { InstallLog.Warn("mo2", "ModOrganizer.ini missing — tools not registered"); return; }
        var lines = new List<string>(File.ReadAllLines(iniPath));
        int sec = lines.FindIndex(l => l.Trim().Equals("[customExecutables]", StringComparison.OrdinalIgnoreCase));
        var existing = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var insertAt = lines.Count;
        if (sec >= 0)
        {
            insertAt = sec + 1;
            int i = sec + 1;
            while (i < lines.Count && !lines[i].Trim().StartsWith('['))
            {
                var line = lines[i];
                var eq = line.IndexOf('=');
                if (eq > 0)
                {
                    var key = line[..eq].Trim();
                    var val = line[(eq + 1)..].Trim();
                    if (key.EndsWith("\\title") && val.Length > 0) existing.Add(val);
                }
                i++;
            }
            insertAt = i; // append right after the last line of the section
        }
        else
        {
            lines.Add("[customExecutables]");
            insertAt = lines.Count;
        }

        var added = new List<string>();
        var refreshed = new List<string>();
        var idx = 1;
        // determine next free index by scanning existing "N\title" keys
        foreach (var l in lines)
        {
            var eq = l.IndexOf('=');
            if (eq > 1 && l.Contains("\\title", StringComparison.OrdinalIgnoreCase)
                && int.TryParse(l[..l.IndexOf('\\')].Trim(), out var n)) idx = Math.Max(idx, n + 1);
        }
        foreach (var t in usable)
        {
            if (existing.Contains(t.Name))
            {
                // Entry from an earlier run: repoint it if the tool now resolves elsewhere
                // (e.g. it has since been moved into the Tools folder).
                if (ResolveTool(instanceDir, gameRoot, t) is var (nexe, ncwd))
                {
                    var ti = lines.FindIndex(l => l.EndsWith("\\title=" + t.Name, StringComparison.Ordinal));
                    if (ti >= 0)
                    {
                        var pfx = lines[ti][..lines[ti].IndexOf("title=", StringComparison.Ordinal)];
                        var bi = lines.FindIndex(l => l.StartsWith(pfx + "binary=", StringComparison.Ordinal));
                        var wi = lines.FindIndex(l => l.StartsWith(pfx + "workingDirectory=", StringComparison.Ordinal));
                        if (bi >= 0 && !lines[bi][(pfx.Length + "binary=".Length)..].Replace('/', Path.DirectorySeparatorChar)
                                .Equals(nexe.Replace('/', Path.DirectorySeparatorChar), StringComparison.OrdinalIgnoreCase))
                        {
                            lines[bi] = pfx + "binary=" + nexe;
                            if (wi >= 0) lines[wi] = pfx + "workingDirectory=" + ncwd;
                            refreshed.Add(t.Name);
                        }
                    }
                }
                continue;
            }
            if (ResolveTool(instanceDir, gameRoot, t) is not var (exe, cwd))
            { InstallLog.Warn("mo2", $"tool {t.Name}: exe not found ({t.Exe}) — skipped"); continue; }
            var args = t.Args is { Count: > 0 } ? string.Join(" ", t.Args) : "";
            added.Add(t.Name);
            lines.Insert(insertAt++, $"{idx}\\title={t.Name}");
            lines.Insert(insertAt++, $"{idx}\\binary={exe}");
            lines.Insert(insertAt++, $"{idx}\\arguments={args}");
            lines.Insert(insertAt++, $"{idx}\\workingDirectory={cwd}");
            lines.Insert(insertAt++, $"{idx}\\steamAppID=");
            idx++;
        }
        if (added.Count == 0 && refreshed.Count == 0) return;
        if (refreshed.Count > 0) InstallLog.Info("mo2", $"repointed {refreshed.Count} existing executables: {string.Join(", ", refreshed)}");
        // refresh the section's size= line (first "size=" inside the section)
        for (int i = 0; i < lines.Count; i++)
        {
            if (!lines[i].Trim().Equals("[customExecutables]", StringComparison.OrdinalIgnoreCase)) continue;
            int j = i + 1;
            while (j < lines.Count && !lines[j].Trim().StartsWith('['))
            {
                if (lines[j].StartsWith("size=", StringComparison.OrdinalIgnoreCase)) { lines[j] = $"size={idx - 1}"; break; }
                j++;
            }
            if (j >= lines.Count || lines[j].Trim().StartsWith('[')) lines.Insert(i + 1, $"size={idx - 1}");
            break;
        }
        File.WriteAllLines(iniPath, lines, new UTF8Encoding(false));
        InstallLog.Info("mo2", $"registered {added.Count} custom executables in ModOrganizer.ini: {string.Join(", ", added)}");
    }
