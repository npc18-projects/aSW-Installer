        "music", "mcm", "interface", "strings", "lstrings", "f4se", "vis", "lod",
        "programs", "shaders", "src", "source", "tools", "bodyslide", "clothes",
        "config", "plugins", "docs", "dialogue", "actors", "terrain", "lodout",
        "occlusion", "distances", "mym", "templates", "workshop", "complex sorter",
